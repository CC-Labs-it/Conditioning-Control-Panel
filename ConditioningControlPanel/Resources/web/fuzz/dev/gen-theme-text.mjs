/* dev/gen-theme-text.mjs - writes data/content/theme-text.js from the approved copy (owner 2026-11-10).
 * The JSON is the source of truth: handoff-1110/tc-theme-text/text-v1.json on the desk (not in the repo).
 *   node dev/gen-theme-text.mjs [path/to/text-v1.json]
 * tests/theme-text.test.mjs compares the two whenever the JSON is around. */
import { readFileSync, writeFileSync } from 'node:fs';

export const SOURCE = 'C:/Projects/Conditioning-Control-Panel---CSharp-WPF/handoff-1110/tc-theme-text/text-v1.json';
const src = process.argv[2] || SOURCE;
const data = JSON.parse(readFileSync(src, 'utf8'));
const lit = (v) => {
  if (Array.isArray(v)) return `Object.freeze([${v.map((s) => JSON.stringify(s)).join(', ')}])`;
  return `Object.freeze({ ${Object.entries(v).map(([k, s]) => `${k}: ${JSON.stringify(s)}`).join(', ')} })`;
};
const out = [
  '/* data/content/theme-text.js - GENERATED by dev/gen-theme-text.mjs from handoff-1110/tc-theme-text/text-v1.json.',
  ' * Edit the JSON, then regenerate. The picked theme\'s own lines for the plain lists in side.js and sweet.js;',
  ' * ui/theme-text.js mixes them in (about 60/40) once a theme is picked. Tokens {cur} {pay}. Pure data. */',
  '',
  '/* The owner\'s Bambi trigger phrases (2026-11-10), as spelled. Bimbo theme only. */',
  `export const BAMBI_TRIGGERS = ${lit(data.bambiTriggers)};`,
  '',
  'export const THEME_TEXT = Object.freeze({',
];
for (const [theme, keys] of Object.entries(data.themes)) {
  out.push(`  ${theme}: Object.freeze({`);
  for (const [key, v] of Object.entries(keys)) out.push(`    ${key}: ${lit(v)},`);
  out.push('  }),');
}
out.push('});', '');
const dest = new URL('../data/content/theme-text.js', import.meta.url);
writeFileSync(dest, out.join('\n'));
console.log('wrote', dest.pathname);
