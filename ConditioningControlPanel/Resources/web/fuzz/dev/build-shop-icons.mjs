// Bake the reviewed WAAPI clips into transparent sheets. The idle image is
// cut from frame zero, including the same fixed-direction shadow as the clip.
// node dev/build-shop-icons.mjs <tc-icons/anim> [output-directory]
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { ICON_CATALOG } from '../ui/icon-catalog.js';

const anim = resolve(process.argv[2]);
const out = resolve(process.argv[3] || fileURLToPath(new URL('../assets/clipart', import.meta.url)));
const require = createRequire(import.meta.url);
let playwright;
try { playwright = require('playwright'); }
catch { playwright = createRequire('C:/wt-fe/e2e/package.json')('playwright'); }
const json = path => JSON.parse(readFileSync(path, 'utf8'));
const shapes = new Set([...Object.values(ICON_CATALOG).map(icon => icon.shape), 'mixer']);
const lamp = json(join(anim, 'shadow.json'));
mkdirSync(out, { recursive: true });
const browser = await playwright.chromium.launch({ channel: 'chrome', headless: true, args: ['--mute-audio'] });
const metadata = {};
try {
  const page = await browser.newPage();
  for (const shape of [...shapes].sort()) {
    if (shape === 'mascot') {
      const baker = fileURLToPath(new URL('./bake-emi-shop-sprite.py', import.meta.url));
      metadata.mascot = JSON.parse(execFileSync(process.env.PYTHON || 'python', [baker, out], { encoding: 'utf8' }));
      continue;
    }
    const spec = json(join(anim, 'specs', shape + '.json'));
    const dir = join(anim, 'parts', shape);
    const casts = json(join(dir, 'casts.json'));
    const sources = {};
    for (const layer of spec.layers) for (const part of layer.parts) {
      const files = [part + '.ns'];
      if ((layer.cast ?? casts[part]) === 'mask') files.push(part + '.cast');
      for (const file of files) sources[file] = 'data:image/webp;base64,' + readFileSync(join(dir, file + '.webp')).toString('base64');
    }
    const result = await page.evaluate(renderSheet, { spec, lamp, casts, sources });
    const encode = (file, png) => execFileSync(process.env.PYTHON || 'python', ['-c',
      "import io,sys;from PIL import Image;Image.open(io.BytesIO(sys.stdin.buffer.read())).save(sys.argv[1],lossless=True,method=2)",
      join(out, file)], { input: Buffer.from(png.split(',')[1], 'base64') });
    encode(shape + '.webp', result.poster);
    encode(shape + '.motion.webp', result.sheet);
    metadata[shape] = result.meta;
  }
  writeFileSync(join(out, 'clips.js'), '// Generated by dev/build-shop-icons.mjs.\nexport const clips = {\n' +
    Object.entries(metadata).map(([name, clip]) => '  ' + JSON.stringify(name) + ': ' + JSON.stringify(clip)).join(',\n') + '\n};\n');
} finally { await browser.close(); }

async function renderSheet({ spec, lamp, casts, sources }) {
  const pixels = 128, margin = 160, edge = pixels + 2 * margin, scale = pixels / 256;
  const frames = Math.max(2, Math.round(spec.ms * 30 / 1000));
  const columns = 8;
  const canvas = (w, h) => Object.assign(document.createElement('canvas'), { width: w, height: h });
  const textures = {};
  await Promise.all(Object.entries(sources).map(async ([id, url]) => {
    const img = new Image(); img.src = url; await img.decode(); textures[id] = img;
  }));
  const layers = spec.layers.map((layer, index) => {
    const art = canvas(256, 256), shade = canvas(256, 256);
    for (const part of layer.parts) {
      const image = textures[part + '.ns'];
      art.getContext('2d').drawImage(image, 0, 0);
      const cast = layer.cast ?? casts[part] ?? true;
      if (cast) shade.getContext('2d').drawImage(cast === 'mask' ? textures[part + '.cast'] : image, 0, 0);
    }
    const element = document.body.appendChild(document.createElement('div'));
    const keys = (layer.keys || [{ at: 0 }, { at: 1 }]).map(k => ({
      offset: k.at, easing: k.ease || 'linear', opacity: k.o ?? 1, zIndex: 10 * (index + 1) + (k.z || 0),
      transform: 'translate(' + (k.x || 0) + 'px,' + (k.y || 0) + 'px) rotate(' + (k.rot || 0) +
        'deg) scale(' + (k.sx ?? k.s ?? 1) + ',' + (k.sy ?? k.s ?? 1) + ')',
    }));
    const track = element.animate(keys, { duration: spec.ms, fill: 'both' });
    track.pause();
    return { art, shade, track, element, origin: layer.origin || [128, 128] };
  });
  const images = [], shadow = canvas(edge, edge);
  let left = margin, top = margin, right = margin + pixels, bottom = right;
  for (let i = 0; i < frames; i++) {
    for (const l of layers) l.track.currentTime = spec.ms * i / (frames - 1);
    const pose = layers.map(l => {
      const style = getComputedStyle(l.element);
      return { ...l, matrix: new DOMMatrix(style.transform), alpha: Number(style.opacity), z: Number(style.zIndex) };
    }).sort((a, b) => a.z - b.z);
    const frame = canvas(edge, edge);
    function paint(ctx, shadowPass) {
      for (const l of pose) {
        const [x, y] = l.origin;
        ctx.save();
        ctx.translate(margin, margin); ctx.scale(scale, scale);
        if (shadowPass) ctx.translate(lamp.dx, lamp.dy);
        ctx.translate(x, y);
        const m = l.matrix;
        ctx.transform(m.a, m.b, m.c, m.d, m.e, m.f);
        ctx.translate(-x, -y);
        ctx.globalAlpha = l.alpha;
        ctx.drawImage(shadowPass ? l.shade : l.art, 0, 0);
        ctx.restore();
      }
    }
    const ctx = frame.getContext('2d', { willReadFrequently: true });
    if (spec.shadow !== false) {
      const s = shadow.getContext('2d');
      s.clearRect(0, 0, edge, edge);
      paint(s, true);
      s.globalCompositeOperation = 'source-in'; s.fillStyle = lamp.invert === undefined ? '#c9c9c9' :
        'rgb(' + Array(3).fill(Math.round(255 * lamp.invert)).join(',') + ')';
      s.fillRect(0, 0, edge, edge); s.globalCompositeOperation = 'source-over';
      ctx.drawImage(shadow, 0, 0);
    }
    paint(ctx, false);
    const data = ctx.getImageData(0, 0, edge, edge).data;
    for (let y = 0; y < edge; y++) for (let x = 0; x < edge; x++) {
      if (!data[(edge * y + x) * 4 + 3]) continue;
      left = Math.min(left, x); top = Math.min(top, y);
      right = Math.max(right, x + 1); bottom = Math.max(bottom, y + 1);
    }
    images.push(frame);
  }
  if (left === 0 || top === 0 || right === edge || bottom === edge) throw Error('Clipped motion: ' + spec.shape);
  left--; top--; right++; bottom++;
  const w = right - left, h = bottom - top;
  const sheet = canvas(w * columns, h * Math.ceil(frames / columns));
  const ctx = sheet.getContext('2d');
  for (let i = 0; i < frames; i++) ctx.drawImage(images[i], left, top, w, h, i % columns * w, Math.floor(i / columns) * h, w, h);
  const poster = canvas(w, h);
  poster.getContext('2d').drawImage(sheet, 0, 0, w, h, 0, 0, w, h);
  for (const l of layers) { l.track.cancel(); l.element.remove(); }
  return { sheet: sheet.toDataURL('image/png'), poster: poster.toDataURL('image/png'),
    meta: { ms: spec.ms, frames, columns, w, h, x: left - margin, y: top - margin } };
}
