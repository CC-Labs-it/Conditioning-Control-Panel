import {mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
const out=resolve(process.argv[2]||'dev/shots/prizes');mkdirSync(out,{recursive:true});
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const {chromium}=createRequire('C:/wt-fe/e2e/package.json')('playwright');
const b=await chromium.launch({channel:'chrome',headless:true,args:['--mute-audio']});
try{
const p=await b.newPage({viewport:{width:390,height:850}}),errors=[];p.on('pageerror',e=>errors.push(e.message));
await p.goto('http://localhost:8807/fuzz/index.html?fresh=1&buy=dispenser,trail');
await p.waitForFunction(()=>document.querySelector('.prize-crank')&&!document.querySelector('.prize-crank').disabled);
await p.evaluate(()=>{const e=fuzz.engine;window.advance=e.step.bind(e);e.step=()=>{};window.go=ms=>{while(ms>0){const d=Math.min(50,ms);advance(d);ms-=d;}};});
const dock=p.locator('.dk[data-fz-owner=dispenser]');
await p.evaluate(()=>{const c=document.querySelector('.dk-chip[data-fz-owner=dispenser]');if(c.getAttribute('aria-expanded')!=='true')c.click();});
const sizeBefore=(await dock.boundingBox()).width;
await dock.locator('.dk-resize').focus();await p.keyboard.press('ArrowRight');
assert((await dock.boundingBox()).width<sizeBefore);
await p.locator('.prize-crank').click();await p.evaluate(()=>go(3200));
const chosen=await p.locator('.prize-machine').getAttribute('data-prize');
await p.evaluate(()=>{fuzz.engine.switches.set('dispenser',false);fuzz.engine.switches.set('dispenser',true);});
await p.waitForFunction(()=>{advance(1);return document.querySelector('.prize-art')?.dataset.capsules==='58';});
assert.equal(await p.locator('.prize-machine').getAttribute('data-prize'),chosen,'remount keeps the chosen color');
await p.evaluate(()=>go(700));
assert.equal(await p.locator('.prize-machine').getAttribute('data-phase'),'catch');
await dock.screenshot({path:`${out}/prize-phone.png`});
await p.evaluate(()=>fuzz.engine.setPaused(true));
await p.locator('.prize-bubble').dispatchEvent('click');
assert.equal(await p.locator('.prize-machine').getAttribute('data-phase'),'catch');
await p.evaluate(()=>{fuzz.engine.setPaused(false);fuzz.ui.setInit({gentle:true});go(50);});
const before=await p.evaluate(()=>fuzz.state.sources.dispenser||0);
await p.locator('.prize-bubble').click();await p.locator('.prize-bubble').dispatchEvent('click');
const earned=await p.evaluate(n=>(fuzz.state.sources.dispenser||0)-n,before);assert(earned>0);
await p.evaluate(()=>go(500));
const alpha=await p.locator('[data-dispenser-effects]').evaluate(c=>c.getContext('2d').getImageData(0,0,c.width,c.height).data.some((v,i)=>i%4===3&&v));assert(!alpha,'Gentle suppresses confetti');
await p.locator('.dk-chip[data-fz-owner=dispenser]').click();
assert.equal(await p.locator('[data-dispenser-effects]').getAttribute('data-reward'),'');
await p.evaluate(()=>{fuzz.engine.switches.set('dispenser',false);fuzz.engine.switches.set('trail',false);});
assert.equal(await p.locator('[data-dispenser-effects],[data-cursor-trail]').count(),0);
assert.deepEqual(errors,[]);console.log('Passed: phone resize, restore mid-drop, pause, Gentle, claim guard, hide and cleanup.');
}finally{await b.close();}
