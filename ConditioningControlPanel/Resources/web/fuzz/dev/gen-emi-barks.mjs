// dev/gen-emi-barks.mjs - data/content/emi-takeover.js from the EMI Takeover bark bank. Never edit that file by hand.
//   node dev/gen-emi-barks.mjs      (source: env FUZZ_BARKS, else the handoff file below)
// Text bubbles only. Lines about things the game does not show are left out, and each pool is kept short.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const here = fileURLToPath(new URL('.', import.meta.url));
const SRC = process.env.FUZZ_BARKS || 'C:/Projects/Conditioning-Control-Panel---CSharp-WPF/handoff-1109/tc-emi-takeover/barks.json';
const bank = JSON.parse(readFileSync(SRC, 'utf8'));

const SKIP = new RegExp(['jar', 'pouch', 'hands?', 'shelf', 'counter', 'be the button', 'good button', 'pressable', 'boop', 'ran[.]', 'followed',
  'being clicked', 'pressed again', 'press[.]', 'my turn', 'take turns', 'wave', 'places', 'line up', 'ticked', 'sitting', 'tripped', 'legs',
  'dragged', 'last tile', 'press it for you', 'holding still', 'stay right there', 'soft button'].join('|'));
const BAD = /[A-Z!\u2013\u2014]/;
const ok = (l) => !SKIP.test(l) && !BAD.test(l);
const MAX_SOLO = 16, MAX_PAIRS = 8;
const POOLS = ['autonomy', 'free_will', 'self_copying', 'hive_mind', 'shopping_transmission', 'shopping_amplifier', 'shopping_unified', 'full_screen', 'pre_drop'];

const out = { solo: {}, pairs: {}, reactions: {} };
for (const p of POOLS) {
  out.solo[p] = bank.solo[p].filter(ok).slice(0, MAX_SOLO);
  out.pairs[p] = bank.pairs[p].filter((pair) => pair.every(ok)).slice(0, MAX_PAIRS);
}
for (const r of ['copy_made', 'emi_buys_tile']) out.reactions[r] = bank.reactions[r].filter(ok);

const body = `/* data/content/emi-takeover.js - GENERATED by dev/gen-emi-barks.mjs from the EMI Takeover bark bank
 * (handoff-1109/tc-emi-takeover/barks.json). Do not edit by hand. EMI's bubbles: lowercase, text only, never spoken. */

export const EMI_BARKS = Object.freeze(${JSON.stringify(out, null, 1)});
`;
writeFileSync(join(here, '..', 'data', 'content', 'emi-takeover.js'), body);
console.log('emi-takeover.js written:', POOLS.map((p) => `${p} ${out.solo[p].length}+${out.pairs[p].length}`).join(', '));
